package codex.recovery;

import OooO0OO.OooOo00;

/** Access to formatting helpers whose package is shadowed inside androidx.navigation. */
public final class NavigationCompat {
    private NavigationCompat() {
    }

    public static String formatBackStackError(StringBuilder prefix, String navigator, String suffix) {
        return OooOo00.OooOOO(prefix, navigator, suffix);
    }

    public static StringBuilder formatDestinationIdError(String prefix, int destinationId, String suffix) {
        return OooOo00.OooOOOo(prefix, destinationId, suffix);
    }

    public static StringBuilder formatDestinationError(String prefix, String destination, String suffix) {
        return OooOo00.OooOOo(prefix, destination, suffix);
    }
}
