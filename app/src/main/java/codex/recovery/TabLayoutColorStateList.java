package codex.recovery;

import android.content.Context;
import android.content.res.ColorStateList;

/** Calls the recovered compatibility resource loader without colliding with TabLayout members. */
public final class TabLayoutColorStateList {
    private TabLayoutColorStateList() {
    }

    public static ColorStateList get(Context context, int resourceId) {
        return OooOoOO.o0O0O00.OooO0OO(context, resourceId);
    }
}
