package com.google.android.material.navigation;

import android.content.Context;
import android.content.res.ColorStateList;
import android.graphics.drawable.Drawable;

/** Calls recovered resource helpers whose package names collide with view fields. */
final class RecoveredNavigationBarItemUtils {
    private RecoveredNavigationBarItemUtils() {
    }

    static void tint(Drawable drawable, ColorStateList tint) {
        OooOooO.o00000OO.OooO0oo(drawable, tint);
    }

    static Drawable getDrawable(Context context, int resourceId) {
        return OooOoOO.o00oO0o.OooO0O0(context, resourceId);
    }
}
